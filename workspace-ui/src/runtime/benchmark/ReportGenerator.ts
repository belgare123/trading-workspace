/**
 * ReportGenerator — generates benchmark reports in JSON, HTML, and Markdown
 *
 * @since 2.0.0
 */

import type { BenchmarkReport } from './types'
import { formatOps } from './types'

export function generateJsonReport(report: BenchmarkReport): string {
  return JSON.stringify(report, null, 2)
}

export function generateMarkdownReport(report: BenchmarkReport): string {
  const lines: string[] = []

  lines.push('# Runtime Benchmark Report')
  lines.push('')
  lines.push(`**Runtime:** v${report.runtimeVersion}`)
  lines.push(`**Date:** ${new Date(report.timestamp).toISOString()}`)
  lines.push(`**Overall Score:** ${report.overallScore} (${report.grade})`)
  lines.push('')

  lines.push('## Runtime Score Breakdown')
  lines.push('')
  lines.push('| Category | Score | Weight |')
  lines.push('|----------|-------|--------|')
  for (const [cat, info] of Object.entries(report.score.categories)) {
    lines.push(`| ${capitalize(cat)} | ${info.score} | ${(info.weight * 100).toFixed(0)}% |`)
  }
  lines.push('')

  lines.push('## Results')
  lines.push('')
  for (const result of report.results) {
    lines.push(`### ${result.success ? '✅' : '❌'} ${result.name}`)
    lines.push('')
    lines.push(`- **Category:** ${result.category}`)
    lines.push(`- **Throughput:** ${formatOps(result.metrics.throughput)} ops/sec`)
    lines.push(`- **Latency:** p50=${result.metrics.latency.p50.toFixed(2)}ms | p95=${result.metrics.latency.p95.toFixed(2)}ms | p99=${result.metrics.latency.p99.toFixed(2)}ms`)
    lines.push(`- **Memory:** ${result.metrics.memory.heapUsedMB.toFixed(1)}MB / ${result.metrics.memory.heapTotalMB.toFixed(1)}MB`)
    lines.push(`- **Dropped:** ${result.metrics.dropped}`)
    lines.push(`- **Duration:** ${result.metrics.duration.toFixed(0)}ms`)
    lines.push(`- **Score:** ${result.score.toFixed(1)}`)

    if (result.error) {
      lines.push(`- **Error:** ${result.error}`)
    }

    if (result.subResults && result.subResults.length > 0) {
      lines.push('')
      lines.push('#### Sub-Results')
      lines.push('')
      lines.push('| Level | Throughput | p50 | p95 | p99 | Memory |')
      lines.push('|-------|-----------|-----|-----|-----|--------|')
      for (const sub of result.subResults) {
        lines.push(`| ${sub.name} | ${formatOps(sub.metrics.throughput)} | ${sub.metrics.latency.p50.toFixed(2)}ms | ${sub.metrics.latency.p95.toFixed(2)}ms | ${sub.metrics.latency.p99.toFixed(2)}ms | ${sub.metrics.memory.heapUsedMB.toFixed(1)}MB |`)
      }
    }
    lines.push('')
  }

  lines.push('---')
  lines.push('*Generated by Runtime Benchmark Suite v2.0.0*')

  return lines.join('\n')
}

export function generateHtmlReport(report: BenchmarkReport): string {
  const resultRows = report.results
    .map(
      (r) => `
    <tr>
      <td>${r.success ? '✅' : '❌'}</td>
      <td>${r.name}</td>
      <td>${formatOps(r.metrics.throughput)}</td>
      <td>${r.metrics.latency.p50.toFixed(2)}ms</td>
      <td>${r.metrics.latency.p95.toFixed(2)}ms</td>
      <td>${r.metrics.latency.p99.toFixed(2)}ms</td>
      <td>${r.metrics.memory.heapUsedMB.toFixed(1)}MB</td>
      <td style="color: ${getScoreColor(r.score)}"><strong>${r.score.toFixed(1)}</strong></td>
    </tr>`,
    )
    .join('\n')

  const categoryRows = Object.entries(report.score.categories)
    .map(
      ([cat, info]) => `
    <tr>
      <td>${capitalize(cat)}</td>
      <td>
        <div class="bar-container">
          <div class="bar" style="width: ${info.score}%"></div>
          <span class="bar-label">${info.score.toFixed(0)}</span>
        </div>
      </td>
      <td>${(info.weight * 100).toFixed(0)}%</td>
    </tr>`,
    )
    .join('\n')

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Runtime Benchmark Report</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', system-ui, sans-serif; background: #0d1117; color: #c9d1d9; padding: 40px; }
    h1 { font-size: 28px; margin-bottom: 8px; }
    h2 { font-size: 20px; margin: 24px 0 12px; }
    .subtitle { color: #8b949e; margin-bottom: 24px; }
    .score-card { display: flex; align-items: center; gap: 24px; background: #161b22; border: 1px solid #30363d; border-radius: 8px; padding: 24px; margin-bottom: 24px; }
    .score-number { font-size: 48px; font-weight: 700; }
    .score-grade { font-size: 24px; padding: 4px 12px; border-radius: 6px; }
    .score-detail { color: #8b949e; }
    .grade-a { color: #3fb950; }
    .grade-b { color: #d29922; }
    .grade-c { color: #f0883e; }
    .grade-d { color: #f85149; }
    .grade-f { color: #da3633; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
    th, td { padding: 10px 12px; text-align: left; border-bottom: 1px solid #30363d; }
    th { background: #161b22; color: #8b949e; font-weight: 600; font-size: 12px; text-transform: uppercase; letter-spacing: 0.5px; }
    td { font-size: 13px; }
    tr:hover td { background: #1c2128; }
    .bar-container { display: flex; align-items: center; gap: 8px; }
    .bar { height: 16px; background: #3fb950; border-radius: 3px; min-width: 4px; }
    .bar-label { font-size: 12px; font-weight: 600; white-space: nowrap; }
    .footer { color: #484f58; font-size: 12px; margin-top: 24px; padding-top: 16px; border-top: 1px solid #21262d; }
  </style>
</head>
<body>
  <h1>Runtime Benchmark Report</h1>
  <p class="subtitle">Runtime v${report.runtimeVersion} — ${new Date(report.timestamp).toISOString()}</p>

  <div class="score-card">
    <div class="score-number ${getGradeClass(report.grade)}">${report.overallScore.toFixed(1)}</div>
    <div class="score-grade ${getGradeClass(report.grade)}">${report.grade}</div>
    <div class="score-detail">Runtime Performance Score</div>
  </div>

  <h2>Score Breakdown</h2>
  <table>
    <thead><tr><th>Category</th><th>Score</th><th>Weight</th></tr></thead>
    <tbody>${categoryRows}</tbody>
  </table>

  <h2>Results</h2>
  <table>
    <thead><tr><th></th><th>Scenario</th><th>Throughput</th><th>p50</th><th>p95</th><th>p99</th><th>Memory</th><th>Score</th></tr></thead>
    <tbody>${resultRows}</tbody>
  </table>

  <div class="footer">Generated by Runtime Benchmark Suite v2.0.0</div>
</body>
</html>`
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

function getScoreColor(score: number): string {
  if (score >= 95) return '#3fb950'
  if (score >= 80) return '#d29922'
  if (score >= 60) return '#f0883e'
  return '#f85149'
}

function getGradeClass(grade: string): string {
  const firstChar = grade.charAt(0)
  switch (firstChar) {
    case 'A': return 'grade-a'
    case 'B': return 'grade-b'
    case 'C': return 'grade-c'
    case 'D': return 'grade-d'
    default: return 'grade-f'
  }
}
